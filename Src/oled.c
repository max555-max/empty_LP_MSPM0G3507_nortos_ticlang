static void oled_scl(uint8_t level)
{
    if (level != 0U) {
        DL_GPIO_setPins(OLED_SCL_PORT, OLED_SCL_PIN_SCL_PIN);
    } else {
        DL_GPIO_clearPins(OLED_SCL_PORT, OLED_SCL_PIN_SCL_PIN);
    }
}

static void oled_sda(uint8_t level)
{
    if (level != 0U) {
        DL_GPIO_setPins(OLED_SDA_PORT, OLED_SDA_PIN_SDA_PIN);
    } else {
        DL_GPIO_clearPins(OLED_SDA_PORT, OLED_SDA_PIN_SDA_PIN);
    }
}

static void oled_dc(uint8_t level)
{
    if (level != 0U) {
        DL_GPIO_setPins(OLED_DC_PORT, OLED_DC_PIN_DC_PIN);
    } else {
        DL_GPIO_clearPins(OLED_DC_PORT, OLED_DC_PIN_DC_PIN);
    }
}

static void oled_rst(uint8_t level)
{
    if (level != 0U) {
        DL_GPIO_setPins(OLED_RST_PORT, OLED_RST_PIN_RST_PIN);
    } else {
        DL_GPIO_clearPins(OLED_RST_PORT, OLED_RST_PIN_RST_PIN);
    }
}

static uint8_t oled_reverse_bits(uint8_t value)
{
    value = (uint8_t)(((value & 0xF0U) >> 4) | ((value & 0x0FU) << 4));
    value = (uint8_t)(((value & 0xCCU) >> 2) | ((value & 0x33U) << 2));
    value = (uint8_t)(((value & 0xAAU) >> 1) | ((value & 0x55U) << 1));
    return value;
}

static void oled_write_byte(uint8_t value)
{
    for (uint8_t i = 0U; i < 8U; i++) {
        oled_scl(0U);
        oled_sda((value & 0x80U) != 0U);
        oled_scl(1U);
        value <<= 1;
    }

    oled_scl(0U);
}

static void oled_write_cmd(uint8_t cmd)
{
    oled_dc(0U);
    oled_write_byte(cmd);
}

static void oled_write_data(uint8_t data)
{
    oled_dc(1U);
    oled_write_byte(data);
}

static uint8_t oled_physical_page(uint8_t page)
{
    if (page >= OLED_PAGES) {
        page = OLED_PAGES - 1U;
    }

    return (uint8_t)((OLED_PAGES - 1U) - page);
}

bool oled_init(void)
{
    oled_rst(1U);
    delay_ms(10U);
    oled_rst(0U);
    delay_ms(20U);
    oled_rst(1U);
    delay_ms(20U);

    oled_write_cmd(0xAEU);
    oled_write_cmd(0xD5U);
    oled_write_cmd(0x50U);
    oled_write_cmd(0xA8U);
    oled_write_cmd(0x3FU);
    oled_write_cmd(0xD3U);
    oled_write_cmd(0x00U);
    oled_write_cmd(0x40U);
    oled_write_cmd(0x8DU);
    oled_write_cmd(0x14U);
    oled_write_cmd(0x20U);
    oled_write_cmd(0x02U);
    oled_write_cmd(0xA1U);
    oled_write_cmd(0xC0U);
    oled_write_cmd(0xDAU);
    oled_write_cmd(0x12U);
    oled_write_cmd(0x81U);
    oled_write_cmd(0xEFU);
    oled_write_cmd(0xD9U);
    oled_write_cmd(0xF1U);
    oled_write_cmd(0xDBU);
    oled_write_cmd(0x30U);
    oled_write_cmd(0xA4U);
    oled_write_cmd(0xA6U);
    oled_write_cmd(0xAFU);

    oled_clear();
    return true;
}

void oled_set_cursor(uint8_t page, uint8_t column)
{
    uint8_t physicalPage = oled_physical_page(page);

    if (column >= OLED_WIDTH) {
        column = OLED_WIDTH - 1U;
    }

    g_cursorPage = page;
    g_cursorColumn = column;

    oled_write_cmd((uint8_t)(0xB0U + physicalPage));
    oled_write_cmd((uint8_t)(0x00U + (column & 0x0FU)));
    oled_write_cmd((uint8_t)(0x10U + ((column >> 4) & 0x0FU)));
}

void oled_clear_line(uint8_t page)
{
    oled_set_cursor(page, 0U);
    for (uint8_t column = 0U; column < OLED_WIDTH; column++) {
        oled_write_data(0x00U);
    }
    oled_set_cursor(page, 0U);
}

void oled_clear(void)
{
    for (uint8_t page = 0U; page < OLED_PAGES; page++) {
        oled_clear_line(page);
    }
    oled_set_cursor(0U, 0U);
}

void oled_print_char(char ch)
{
    const uint8_t *glyph;

    if ((ch < ' ') || (ch > '~')) {
        ch = '?';
    }

    if ((g_cursorColumn + OLED_CHAR_W) > OLED_WIDTH) {
        return;
    }

    glyph = g_font5x7[(uint8_t)ch - (uint8_t)' '];
    for (uint8_t i = 0U; i < OLED_FONT_W; i++) {
        oled_write_data(oled_reverse_bits(glyph[i]));
    }
    oled_write_data(0x00U);
    g_cursorColumn = (uint8_t)(g_cursorColumn + OLED_CHAR_W);
}

void oled_print_string(const char *text)
{
    while ((text != 0) && (*text != '\0')) {
        oled_print_char(*text);
        text++;
    }
}

void oled_print_int(int32_t value)
{
    char digits[12];
    uint8_t index = 0U;
    uint32_t magnitude;

    if (value < 0) {
        oled_print_char('-');
        magnitude = (uint32_t)(-(value + 1)) + 1U;
    } else {
        magnitude = (uint32_t)value;
    }

    do {
        digits[index++] = (char)('0' + (magnitude % 10U));
        magnitude /= 10U;
    } while ((magnitude != 0U) && (index < sizeof(digits)));

    while (index > 0U) {
        oled_print_char(digits[--index]);
    }
}

void oled_print_float(float value, uint8_t decimals)
{
    int32_t integer;
    float fraction;

    if (decimals > 3U) {
        decimals = 3U;
    }

    if (value < 0.0f) {
        oled_print_char('-');
        value = -value;
    }

    integer = (int32_t)value;
    fraction = value - (float)integer;

    oled_print_int(integer);
    if (decimals == 0U) {
        return;
    }

    oled_print_char('.');
    for (uint8_t i = 0U; i < decimals; i++) {
        fraction *= 10.0f;
        oled_print_char((char)('0' + (int32_t)fraction));
        fraction -= (float)((int32_t)fraction);
    }
}

void oled_print_hex_u8(uint8_t value)
{
    static const char hex[] = "0123456789ABCDEF";

    oled_print_string("0x");
    oled_print_char(hex[(value >> 4) & 0x0FU]);
    oled_print_char(hex[value & 0x0FU]);
}
